def main(src):
    files = sorted(f for f in os.listdir(src) if f.endswith('.jpg'))
    assert len(files) == 232, len(files)
    out = []
    for a, b, bld, floor, memo in PLAN:
        group = list(range(a, b + 1))
        for k, i in enumerate(group):
            # id = 촬영 시각 (s월일_시분초) — 건물·층을 고쳐도 사진 파일 이름은 그대로
            nid = 's' + files[i][8:19]
            shown = ('지하' + floor[1:] + '층') if floor and floor.startswith('B') else floor  # B1 → 지하1층
            where = ' '.join(x for x in [NAME[bld], shown if bld != 'outdoor' else '', memo] if x)
            out.append({
                'id': nid, 'src': files[i][:-4], 'b': bld, 'f': floor, 'g': f'{a}',
                't': f"{where}{f' ({k + 1}/{len(group)})' if len(group) > 1 else ''}",
                # 가운데 사진 = 엘리베이터 앞(층에 내리자마자)일 가능성이 높아 그 층 대표 지점으로 쓴다
                **({'c': 1} if k == (len(group) - 1) // 2 else {}),
            })
    dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'floor-panos.json')
    # 한 줄에 한 지점 — 사람이 고치기 쉽게
    open(dst, 'w').write('[\n' + ',\n'.join(json.dumps(r, ensure_ascii=False) for r in out) + '\n]\n')
    print(len(out), '지점 →', os.path.normpath(dst))


if __name__ == '__main__':
    main(sys.argv[1])
